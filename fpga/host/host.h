/* The native host: machine-video + rom + one cart, each translated by wasm2c
 * (-n machine / -n rom / -n cart), sharing ONE linear memory, driven exactly as
 * apps/scene_hash.mjs drives the wasm modules. See README.md. */
#ifndef HOST_H
#define HOST_H

/* The board's split images (decisions.md 2026-10-15) compile this header two more ways:
 * ZM_SPLIT_SYS, the system image, which has no cart.h (its cart is the cart image's, reached
 * through zm_cart, the image's header); ZM_SPLIT_CART, the cart image, which has only cart.h
 * and never looks inside the system's env. HOST_CART(e) is the cart instance either way. */
#ifndef ZM_SPLIT_CART
#include "machine.h"
#include "rom.h"
#endif
#ifndef ZM_SPLIT_SYS
#include "cart.h"
#endif

#if defined(ZM_SPLIT_SYS)
typedef struct w2c_cart w2c_cart;
struct w2c_env {
    wasm_rt_memory_t memory;
    w2c_machine machine;
    w2c_rom rom;
    w2c_cart* cart; /* calloc'd, zm_cart->inst_bytes (cycles/bsys.c) */
};
#define HOST_CART(e) ((e)->cart)
#elif !defined(ZM_SPLIT_CART)
/* wasm2c's generated code names every import's owner `struct w2c_env`. All three
 * modules import from "env", so this one struct is the whole host: the shared
 * memory plus the instances that serve each other's imports. */
struct w2c_env {
    wasm_rt_memory_t memory;
    w2c_machine machine;
    w2c_rom rom;
    w2c_cart cart;
};
#define HOST_CART(e) (&(e)->cart)
#endif

/* Generated per cart by tools/host_gen.py (env.c). */
extern const uint32_t host_pages;      /* SHARED_PAGES from machine/sdk/memmap.zig */
extern const uint32_t host_rom_high;   /* romRam(rom.wasm).high ?? 0, docs/wasm_hiwater.js */
extern const uint32_t host_cart_high;  /* cartRam(cart.wasm).high ?? 0 */

/* A cart export callable from --call. Arguments arrive as JS Numbers (double)
 * and are converted the way the JS-to-wasm boundary converts them. */
typedef struct host_export {
    const char* name;
    void (*fn)(struct w2c_env* e, const double* args);
} host_export;

extern const host_export host_exports[]; /* NULL-terminated */

/* The cart's song bridge (libs/zig/zigos.zig, apps/zig/demo_main.zig exports), as
 * docs/sealed-loader.js polls it each frame; a NULL entry: the cart has no such
 * export. Generated by tools/host_gen.py; read only by the audio side (haudio.h). */
typedef struct host_song_bridge {
    u32 (*poll)(w2c_cart*);          /* pollSongRequest */
    u32 (*name_ptr)(w2c_cart*);      /* songNamePtr */
    u32 (*name_len)(w2c_cart*);      /* songNameLen */
    u32 (*tune)(w2c_cart*);          /* songTune */
    u32 (*sndh_poll)(w2c_cart*);     /* pollSndhCalls */
    u32 (*sndh_d0)(w2c_cart*, u32);  /* sndhCallD0 */
    u32 (*sndh_name_ptr)(w2c_cart*); /* sndhCallNamePtr */
    u32 (*sndh_name_len)(w2c_cart*); /* sndhCallNameLen */
    u32 (*sfx_poll)(w2c_cart*);      /* pollSfx: the effects queue (libs/zig/sfx_queue.zig) */
    u32 (*sfx_entries)(w2c_cart*);   /* sfxEntriesPtr */
} host_song_bridge;

extern const host_song_bridge host_songs;

/* The cart's input exports (apps/zig/demo_main.zig), as docs/sealed-loader.js calls them;
 * a NULL entry: the cart has no such export. Generated by tools/host_gen.py; called by
 * host/input_bridge.c (the glass's events on the board, a script on the native host). */
typedef struct host_input_bridge {
    u32 (*owns_keyboard)(w2c_cart*);             /* ownsKeyboard */
    void (*input)(w2c_cart*, u32);               /* input(dir) */
    void (*input_release)(w2c_cart*, u32);       /* inputRelease(dir) */
    void (*key)(w2c_cart*, u32);                 /* key(code) */
    void (*key_up)(w2c_cart*, u32);              /* keyUp(code) */
    u32 (*shade)(w2c_cart*, u32);                /* setShadeMode(n) */
    void (*pointer)(w2c_cart*, u32, u32, u32);   /* pointer(x, y, buttons) */
} host_input_bridge;

extern const host_input_bridge host_input;

/* The cart's disk exports (apps/zig/demo_main.zig), as docs/sealed-loader.js calls them for
 * GEM over a data disk; a NULL entry: the cart has no such export. Generated by
 * tools/host_gen.py; called by host/disk_app.h. */
typedef struct host_disk_app_bridge {
    void (*insert_disk)(w2c_cart*, u32); /* insertDisk(1) */
    u32 (*is_booted)(w2c_cart*);         /* isBooted */
    u32 (*dir_ptr)(w2c_cart*);           /* diskDirPtr */
    void (*set_count)(w2c_cart*, u32);   /* setDiskFileCount(n) */
    u32 (*poll)(w2c_cart*);              /* pollCartRequest */
    u32 (*tag_ptr)(w2c_cart*);           /* getCartTagPtr */
    u32 (*tag_len)(w2c_cart*);           /* getCartTagLen */
} host_disk_app_bridge;

extern const host_disk_app_bridge host_dapp;

/* The cart's audio-state fields (getYmRegsPointer, getAudioModePointer, getSongMsPointer) to the
 * HOST_AUDIO_MIRROR hook: the board firmware's mirror (cycles/bmirror.h), else the no-op. Generated
 * by tools/host_gen.py; called by host/boot.c after the cart's instantiation. The lean cart
 * image makes the same call through the system table (tools/host_split.py, table 1.2). */
void host_audio_mirror_bind(struct w2c_env* e);

#define HOST_MAX_ARGS 16

/* ToInt32: what wasm receives for an i32 parameter given a JS Number. */
u32 host_to_i32(double x);

#ifdef ZM_SPLIT_SYS /* what env.c defined by name, the system image takes from the cart's header */
#include "zm_sys_abi.h"
#define host_cart_high (zm_cart->cart_high)
#define host_exports (zm_cart->exports)
#define host_songs (*zm_cart->songs)
#define host_input (*zm_cart->input)
#define host_dapp (*zm_cart->dapp)
#endif

#endif
