/* The BARD MP3 study's bench (fpga/review/MP3_BARD_STUDY.md): one decoder behind a three-call adapter,
 * the same loop on BARD (mp3bench.c, snd-cbench) and on the host (tools/mp3_bard_host.c), so the two
 * print the same per-frame PCM hash. The decoders are third-party (tools/mp3_bard_fetch.sh) and never
 * committed; the adapters (mp3a_helix.c, mp3a_pv.c) are ours. */
#ifndef ZM_MP3BENCH_H
#define ZM_MP3BENCH_H

#include <stdint.h>

#define MP3_MAX_PCM (1152 * 2) /* one MPEG-1 frame, stereo */

typedef struct {
    const char *name;
    const uint8_t *data;
    uint32_t len;
} mp3_stream_t;

/* The streams the bench decodes (generated by tools/mp3_bard_streams.sh). */
extern const mp3_stream_t mp3_streams[];
extern const int mp3_nstreams;

/* The adapter: open a decoder; decode the next frame from *p (advancing *p and *left) into pcm
 * (interleaved), returning samples per channel, 0 for a frame that made no PCM yet (bit reservoir),
 * < 0 at the end or on an error; close it. */
extern const char mp3a_name[];
void *mp3a_open(void);
int mp3a_frame(void *d, const uint8_t **p, uint32_t *left, int16_t *pcm, int *nch, int *rate);
void mp3a_close(void *d);

/* FNV-1a over a frame's PCM: BARD's decode must match the host's bit for bit. */
static inline uint32_t mp3_hash(const int16_t *pcm, int n) {
    uint32_t h = 2166136261u;
    for (int i = 0; i < n; i++) {
        h = (h ^ (uint16_t)pcm[i]) * 16777619u;
    }
    return h;
}

/* The byte length of the Layer III frame whose header is at p (0 if it is not one): pvmp3 wants whole
 * frames, as a streaming player hands them from its ring. One divide a frame. */
static inline uint32_t mp3_frame_len(const uint8_t *p) {
    static const uint16_t kbps[2][15] = {{0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320},
                                         {0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160}};
    static const uint16_t rate[3] = {44100, 48000, 32000};
    if (p[0] != 0xFF || (p[1] & 0xE6) != 0xE2) return 0; /* sync, Layer III */
    uint32_t ver = (p[1] >> 3) & 3, bi = p[2] >> 4, si = (p[2] >> 2) & 3, pad = (p[2] >> 1) & 1;
    if (ver == 1 || bi == 0 || bi == 15 || si == 3) return 0;
    uint32_t sr = rate[si] >> (ver == 3 ? 0 : ver == 2 ? 1 : 2), lsf = ver != 3;
    return (lsf ? 72000u : 144000u) * kbps[lsf][bi] / sr + pad;
}

#endif
