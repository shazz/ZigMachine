/* The BARD SID study's bench (fpga/review/SID_BARD_STUDY.md): cRSID (Hermit's light SID + 6502
 * player) renders a tune 60 Hz frame by 60 Hz frame, the same loop on BARD (sidbench.c, snd-cbench)
 * and on the host (tools/sid_bard_host.c), so both print the same per-frame PCM hash. cRSID and the
 * HVSC tunes stay local (tools/sid_bard_fetch.sh, prototypes/sid_re/): never committed. */
#ifndef ZM_SIDBENCH_H
#define ZM_SIDBENCH_H

#include <stdint.h>

#include "libcRSID.h"

typedef struct {
    const char *name;
    const uint8_t *data;
    uint32_t len;
    int subtune; /* 1-based, 0 = the header's default */
} sid_tune_t;

/* The tunes (generated by tools/sid_bard_bench.sh from prototypes/sid_re/tunes/). */
extern const sid_tune_t sid_tunes[];
extern const int sid_ntunes;

#ifndef SID_RATE
#define SID_RATE 44100
#endif
#ifndef SID_HQ
#define SID_HQ 1 /* cRSID's default: cycle-based waves, 5x oversampled; 0 = its light engine */
#endif
#define SID_FRAME (SID_RATE / 60) /* samples in one 60 Hz frame */

/* Starts a tune (cRSID copies the file into its C64 RAM: the data must be writable). */
static inline int sid_start(const sid_tune_t *t, uint8_t *copy) {
    static int up;
    if (!up && !cRSID_init(SID_RATE, SID_FRAME)) return 1;
    up = 1;
    for (uint32_t i = 0; i < t->len; i++) copy[i] = t->data[i];
    cRSID_SIDheader *h = cRSID_processSIDfileData(copy, (int)t->len);
    if (!h) return 2;
    cRSID.HighQualitySID = SID_HQ;
    cRSID_initSIDtune(h, (char)(t->subtune ? t->subtune : h->DefaultSubtune));
    return 0;
}

/* One frame of PCM, s16 stereo interleaved (cRSID mixes one SID to both sides). Through
 * cRSID_generateSound, the library's buffer filler: it refreshes the shadow settings
 * (HighQualitySID...) that cRSID_generateSample alone would not. */
static inline void sid_frame(int16_t *pcm) {
    cRSID_generateSound((unsigned char *)pcm, SID_FRAME * 4);
}

/* FNV-1a over a frame's PCM: BARD's render must match the host's bit for bit. */
static inline uint32_t sid_hash(const int16_t *pcm, int n) {
    uint32_t h = 2166136261u;
    for (int i = 0; i < n; i++) h = (h ^ (uint16_t)pcm[i]) * 16777619u;
    return h;
}

#endif
