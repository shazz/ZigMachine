"""The fast edit -> board loop's file edits and reports (soc/openxc7_fast.py,
tools/build_times.py, tools/sweep.py): pure text, no toolchain."""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from types import ModuleType

import pytest

from soc import openxc7_fast

FPGA = Path(__file__).resolve().parent.parent
LITEX_SCRIPT = """# Autogenerated by LiteX
set -e
yosys  -l top.rpt top.ys
nextpnr-xilinx --json top.json --xdc top.xdc --fasm top.fasm --seed 1
fasm2frames --part p top.fasm > top.frames
xc7frames2bit --part_file y --frm_file top.frames --output_file top.bit
"""
PNR_LOG = """Info: Pre-placed: 9000 cell(s) pinned to their reference bel, 120 not in this design; 800 tile(s) closed.
Info: Max frequency for clock 'sys_clk': 140.00 MHz (PASS at 100.00 MHz)
Info: HeAP Placer Time: 2.50s
Info: SA placement time 0.70s
Info: Router2 time 30.25s
Info: Router1 time 1.25s
Info: Max frequency for clock 'sys_clk': 101.50 MHz (PASS at 100.00 MHz)
Info: Max frequency for clock 'comp_clk': 118.40 MHz (FAIL at 125.00 MHz)
"""


def tool(name: str) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, FPGA / f"tools/{name}.py")
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def test_time_stages_wraps_every_tool_line_after_set_e(tmp_path: Path) -> None:
    script = tmp_path / "build_top.sh"
    script.write_text(LITEX_SCRIPT)
    openxc7_fast.time_stages(script)
    lines = script.read_text().splitlines()
    assert lines[2].startswith("zm_stage()") and lines[3] == ": > stages.txt"
    assert [ln.split()[1] for ln in lines if ln.startswith("zm_stage ")] == ["synth", "pnr", "frames", "bit"]


def test_time_stages_sees_through_the_pnr_timeout(tmp_path: Path) -> None:
    script = tmp_path / "build_top.sh"
    script.write_text(LITEX_SCRIPT.replace("nextpnr-xilinx", "timeout 1500 nextpnr-xilinx"))
    openxc7_fast.time_stages(script)
    assert "zm_stage pnr timeout 1500 nextpnr-xilinx --json" in script.read_text()


def test_time_stages_refuses_a_script_without_nextpnr(tmp_path: Path) -> None:
    script = tmp_path / "build_top.sh"
    script.write_text("set -e\nyosys x.ys\n")
    with pytest.raises(ValueError, match="no nextpnr"):
        openxc7_fast.time_stages(script)


def test_stable_names_adds_autoname_once_and_marks_the_directory(tmp_path: Path) -> None:
    ys = tmp_path / "top.ys"
    ys.write_text("read_verilog top.v\nsynth_xilinx -flatten -arch xc7 -top top\nwrite_json  top.json")
    openxc7_fast.stable_names(ys)
    openxc7_fast.stable_names(ys)
    text = ys.read_text()
    assert text.count("autoname") == 1 and text.index("autoname") < text.index("write_json")
    assert (tmp_path / openxc7_fast.STABLE_MARK).exists()


def reuse_dirs(tmp_path: Path, stable: bool) -> tuple[Path, Path]:
    base, gw = tmp_path / "base", tmp_path / "gw"
    for d in (base, gw):
        d.mkdir()
    (base / "top_placement.json").write_text("{}")
    (base / "top.json").write_text("{}")
    if stable:
        (base / openxc7_fast.STABLE_MARK).write_text("")
    (gw / "build_top.sh").write_text(LITEX_SCRIPT)
    openxc7_fast.time_stages(gw / "build_top.sh")
    return base, gw


def test_reuse_refuses_a_base_that_is_not_a_stable_names_build(tmp_path: Path) -> None:
    base, gw = reuse_dirs(tmp_path, stable=False)
    with pytest.raises(openxc7_fast.ReuseBaseError, match="not a stable-names build"):
        openxc7_fast.add_reuse(gw / "build_top.sh", base, "top")


def test_reuse_refuses_a_base_without_a_placement_dump(tmp_path: Path) -> None:
    base, gw = reuse_dirs(tmp_path, stable=True)
    (base / "top_placement.json").unlink()
    with pytest.raises(openxc7_fast.ReuseBaseError, match="no top_placement.json"):
        openxc7_fast.add_reuse(gw / "build_top.sh", base, "top")


def test_reuse_filters_between_synthesis_and_pnr_then_pins(tmp_path: Path) -> None:
    base, gw = reuse_dirs(tmp_path, stable=True)
    openxc7_fast.add_reuse(gw / "build_top.sh", base, "top")
    lines = (gw / "build_top.sh").read_text().splitlines()
    stages = [ln.split()[1] for ln in lines if ln.startswith("zm_stage ")]
    assert stages == ["synth", "freeze", "pnr", "frames", "bit"]
    assert "-o preplaced=reuse_preplaced.tsv" in next(ln for ln in lines if ln.startswith("zm_stage pnr"))
    assert (gw / "reuse_base_placement.json").exists() and (gw / "reuse_base_netlist.json").exists()


def test_freeze_pins_only_cells_whose_type_and_nets_did_not_change(tmp_path: Path) -> None:
    fz = tool("freeze_placement")

    def netlist(path: Path, b_input: str) -> None:
        cells = {"a": {"type": "FDRE", "connections": {"D": [2], "Q": [3]}},
                 "b": {"type": "LUT2", "connections": {"I0": [3], "I1": [4 if b_input == "x" else 5], "O": [2]}}}  # fmt: skip
        nets = {"d": {"bits": [2]}, "q": {"bits": [3]}, "x": {"bits": [4]}, "y": {"bits": [5]}}
        path.write_text(
            json.dumps({"modules": {"top": {"attributes": {"top": "1"}, "cells": cells, "netnames": nets}}})
        )

    netlist(tmp_path / "a.json", "x")
    netlist(tmp_path / "b.json", "y")
    assert fz.unchanged(tmp_path / "a.json", tmp_path / "b.json") == {"a"}
    assert fz.unchanged(tmp_path / "a.json", tmp_path / "a.json") is None  # the same netlist: pin it all


def test_freeze_pins_a_slice_whole_or_not_at_all() -> None:
    fz = tool("freeze_placement")
    cells = {"ff": {"site": "SLICE_X1Y1"}, "lut": {"site": "SLICE_X1Y1"}, "ram": {"site": "RAMB18_X0Y0"}}
    assert fz.whole_sites(cells, {"ff", "ram"}) == {"ram"}


def test_freeze_never_pins_the_luts_feeding_a_carry_chain(tmp_path: Path) -> None:
    fz = tool("freeze_placement")
    cells = {"lut": {"type": "LUT2", "port_directions": {"O": "output"}, "connections": {"O": [2]}},
             "cy": {"type": "CARRY4", "port_directions": {"S": "input"}, "connections": {"S": [2]}},
             "ff": {"type": "FDRE", "port_directions": {"Q": "output"}, "connections": {"Q": [3]}}}  # fmt: skip
    nets = {"s": {"bits": [2]}, "q": {"bits": [3]}}
    (tmp_path / "n.json").write_text(
        json.dumps({"modules": {"t": {"attributes": {"top": "1"}, "cells": cells, "netnames": nets}}})
    )
    _, clustered = fz.signatures(tmp_path / "n.json")
    assert clustered == {"lut", "cy"}


def test_build_times_reports_stages_split_fmax_and_reuse(tmp_path: Path) -> None:
    bt = tool("build_times")
    (tmp_path / "stages.txt").write_text("synth 10.0 55.5\npnr 55.5 100.0\ngen 0 12.0\n")
    (tmp_path / "pnr.log").write_text(PNR_LOG)
    rows, record = bt.summary(bt.read_stages(tmp_path / "stages.txt"), bt.read_pnr(tmp_path / "pnr.log"))
    assert "synth=45.5 pnr=44.5 gen=12.0 place=3.2 route=31.5 total=102.0" in record
    assert "fmax=sys_clk:101.50,comp_clk:118.40" in record and "pinned=9000" in record
    assert any("reuse   9000 cells pinned" in r for r in rows)


def test_build_times_without_stages_fails_loud(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    bt = tool("build_times")
    monkeypatch.setattr(sys, "argv", ["build_times.py", str(tmp_path), "--log", str(tmp_path / "t.txt")])
    assert bt.main() == 1
    assert not (tmp_path / "t.txt").exists()


def test_sweep_prepares_a_pnr_only_script_with_its_seed_and_no_replay(tmp_path: Path) -> None:
    sw = tool("sweep")
    src = tmp_path / "gw"
    src.mkdir()
    for ext in ("json", "xdc"):
        (src / f"top.{ext}").write_text("{}")
    script = LITEX_SCRIPT.replace("--seed 1", "--seed 1 -o preplaced=/x/reuse.tsv").replace(
        "nextpnr", "timeout 1500 nextpnr"
    )
    (src / "build_top.sh").write_text(script)
    d = sw.prepare(src, "top", 7, tmp_path / "out")
    text = (d / "build_top.sh").read_text()
    assert "yosys" not in text and "preplaced" not in text and "--seed 7" in text
    assert "zm_stage pnr timeout 900 nextpnr" in text
    assert (d / "top.json").resolve() == src / "top.json"


def test_sweep_verdict_takes_the_routed_report_and_flags_a_failing_clock(tmp_path: Path) -> None:
    sw = tool("sweep")
    (tmp_path / "pnr.log").write_text(PNR_LOG)
    ok, worst, text = sw.verdict(tmp_path)
    assert (ok, round(worst, 3)) == (False, round(118.4 / 125, 3))
    assert text == "sys_clk 101.5, comp_clk 118.4 FAIL"
