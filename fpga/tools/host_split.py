"""The board's split env (decisions.md 2026-10-15): what tools/host_gen.py's env.c does for
the monolithic image, cut along the system table (fpga/cycles/sys_abi.txt).

    uv run python tools/host_split.py system build/host/common/sys_env.c       # once: the system image's
    uv run python tools/host_split.py cart build/host/<tag> --cart ../docs/demo-<tag>.wasm   # cart_env.c

The system's: the machine's and the ROM's env imports resolved as env.c resolves them
(env.hblDispatch through the cart header), the drive, and zm_sys_table, the entries the
cart image calls. The cart's: each of its env imports either a table call (a ROM or
machine export, hostMicros, diskReadBlock) or scene_hash.mjs's no-op stub inline, its
bridges and --call table as env.c has them, and its header (zm_cart_hdr) at the image's
start. Both sides take every type from the wasm2c headers and refuse an import the table
does not have, or has with another type.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

FPGA = Path(__file__).resolve().parent.parent
ROOT = FPGA.parent
sys.path.insert(0, str(FPGA / "tools"))
import wasm_info  # after the path insert
from host_bridges import (HOST_DEFAULTS, HOST_ENTRIES, STREAM, disk_app_bridge, export_table, input_bridge, mirror_args,
                          song_bridge)
from host_gen import DRIVE, DRIVE_DEF, HOOK_DEFAULTS, HOOKS, SPAN_HOOKS, decls, forwarder, imports, link_check, resolve
from sys_abi_c import checked, env_rows
from sys_abi_c import forwarder as table_call
from sys_abi_layout import RUNTIME

NEEDED = ("boot", "skipBoot", "frame", "isPlaneEnabled", "hblDispatch")  # what bmain.c and boot call by name


def pages() -> int:
    sys.path.insert(0, str(FPGA / "gen"))
    from memmap import SHARED_PAGES  # generated from machine/sdk/memmap.zig

    return SHARED_PAGES


def table_rows(m, exports: dict[str, dict]) -> dict[str, tuple[str, str, list[str]]]:
    """name -> (owner, ret, params) per env entry, each held to its wasm2c declaration."""
    out = {}
    for name, owner, ret, params in env_rows(m):
        have = HOST_ENTRIES.get(name, (None, None))[:2] if owner == "host" else exports[owner].get(name)
        if have != (ret, params):
            sys.exit(f"host_split: sys_abi.txt's env.{name} is not {owner}.h's {exports[owner].get(name)}")
        out[name] = (owner, ret, params)
    return out


def system_env(out: Path) -> None:
    common = out.parent
    headers = {"machine": common / "machine.h", "rom": common / "rom.h"}
    link_check({"machine": ROOT / "docs/machine-video.wasm", "rom": ROOT / "docs/rom.wasm"}, pages())
    exports = {who: decls(h, who) for who, h in headers.items()}
    rows = table_rows(checked(), exports)
    rom_high = wasm_info.high_water((ROOT / "docs/rom.wasm").read_bytes()) or 0
    parts = ["/* Generated by fpga/tools/host_split.py: do not edit. The system image's env. */",
             '#include <assert.h>\n#include <math.h>\n#include <stdbool.h>\n#include <string.h>\n#include "host.h"\n#include "disk.h"\n',
             SPAN_HOOKS, HOOK_DEFAULTS, HOST_DEFAULTS, DRIVE_DEF, f"const uint32_t host_pages = {pages()}u;",
             f"const uint32_t host_rom_high = {rom_high:#x}u;\n"]  # fmt: skip
    own = imports(headers)
    for name, (ret, params, who) in sorted(own.items()):
        if name == "hblDispatch":
            parts.append(hbl(params))
        elif name != "memory":
            parts.append(forwarder(name, ret, params, resolve(name, who, exports), exports))
    for name, (owner, ret, params) in rows.items():
        if name not in own:  # a host entry is its hook macro: host/hstream.h, cycles/bmirror.h, -include'd
            target = None if owner == "host" else owner
            parts.append(
                "static " + forwarder(name, ret, params, target, exports).replace(f" w2c_env_{name}(", f" t_{name}(")
            )
    parts.append(system_tail(rows, own))
    out.write_text("\n".join(parts))


def hbl(params: list[str]) -> str:
    args = "".join(f", {t} a{i}" for i, t in enumerate(params))
    call = ", ".join(f"a{i}" for i in range(len(params)))
    return (f"void w2c_env_hblDispatch(struct w2c_env* e{args}) {{ HOST_SPAN_ENTER(HOST_SPAN_CART); "
            f"zm_cart->hbl_dispatch(e->cart, {call}); HOST_SPAN_LEAVE(); }}\n")  # fmt: skip


def system_tail(rows: dict, own: dict) -> str:
    """The two host hooks the table carries, and the table."""
    rt = [f"    [ZM_RT_{s}] = (zm_fn){s}," for s, *_ in RUNTIME]
    env = [f"    [ZM_ENV_{n}] = (zm_fn){'w2c_env_' if n in own else 't_'}{n}," for n in rows]
    return (
        "uint32_t zm_host_micros(void) { return HOST_MICROS(); }\n"
        "uint32_t zm_disk_read(struct w2c_env* e, uint32_t block, uint32_t dst) {\n"
        "    int64_t n = host_disk_read(&host_disk, block, dst, e->memory.data, e->memory.size);\n"
        "    if (n < 0) wasm_rt_trap(WASM_RT_TRAP_OOB); /* the JS's RangeError */\n"
        "    return (uint32_t)n;\n}\n\n"
        "const zm_sys_table zm_sys_table_v = {ZM_SYS_MAGIC, ZM_SYS_ABI_VERSION, ZM_SYS_COUNT, {\n"
        + "\n".join(rt + env)
        + "\n}};\n"
    )


def cart_import(name: str, ret: str, params: list[str], target: str | None, rows: dict, exports: dict) -> str:
    if (name in HOOKS and (ret, params) != (HOOKS[name][0], [])) or (name in DRIVE and (ret, params) != DRIVE[name]):
        sys.exit(f"host_split: env.{name} is {ret}{params}, not the host's own")
    if name in HOOKS:
        call = "((uint32_t (*)(void))zm_sys->fn[ZM_RT_zm_host_micros])()"
        return f"{ret} w2c_env_{name}(struct w2c_env* e) {{ (void)e; return {call}; }}\n"
    if name in DRIVE:
        return table_call(f"w2c_env_{name}", ret, ["struct w2c_env*", *params], "ZM_RT_zm_disk_read")
    if name in STREAM:  # the stream ring is the system's (table 1.1): a 1.0 system refuses this cart
        if rows.get(name) != ("host", ret, params):
            sys.exit(f"host_split: env.{name} ({ret}{params}) is not the system table's host entry")
        return table_call(f"w2c_env_{name}", ret, ["struct w2c_env*", *params], f"ZM_ENV_{name}")
    if target is None:
        return forwarder(name, ret, params, None, exports)
    if rows.get(name) != (target, ret, params):
        sys.exit(f"host_split: env.{name} ({target} {ret}{params}) is not in the system table as sys_abi.txt has it")
    return table_call(f"w2c_env_{name}", ret, ["struct w2c_env*", *params], f"ZM_ENV_{name}")


def cart_env(build: Path, wasm: Path) -> None:
    headers = {"machine": build.parent / "common/machine.h", "rom": build.parent / "common/rom.h"}
    exports = {who: decls(h, who) for who, h in headers.items()}
    exports["cart"] = decls(build / "cart.h", "cart")
    if missing := [n for n in NEEDED if n not in exports["cart"]]:
        sys.exit(f"host_split: {wasm.name} exports no {', '.join(missing)}")
    link_check({"cart": wasm}, pages())
    rows = table_rows(checked(), exports)
    parts = [f"/* Generated by fpga/tools/host_split.py for {wasm.name}: do not edit. The cart image's env. */",
             '#include <math.h>\n#include "host.h"\n#include "baudio.h"\n#include "zm_sys_abi.h"\n',
             "static w2c_cart* g_cart; /* the instance the system calloc'd, from instantiate */\n"]  # fmt: skip
    for name, (ret, params, _) in sorted(imports({"cart": build / "cart.h"}).items()):
        if name != "memory":
            parts.append(cart_import(name, ret, params, resolve(name, {"cart"}, exports), rows, exports))
    cart = exports["cart"]
    parts += [export_table(cart, "g_cart"), song_bridge(cart), input_bridge(cart), disk_app_bridge(cart)]
    parts.append(cart_header(wasm, cart))
    (build / "cart_env.c").write_text("\n".join(parts))


def cart_mirror(cart: dict[str, tuple[str, list[str]]]) -> str:
    """The audio-state fields to the system once instantiated (table 1.2's hostAudioMirror,
    host_bridges.MIRROR); skipped by a shorter table, though the version rule refuses one first."""
    call = table_call("c_mirror", "void", ["struct w2c_env*", "u32", "u32", "u32"], "ZM_ENV_hostAudioMirror")
    return (f"static {call}static void c_audio_mirror(w2c_cart* c, struct w2c_env* e) {{\n"
            f"    if (zm_sys->count > ZM_ENV_hostAudioMirror) c_mirror(e, {mirror_args(cart, 'c')});\n}}\n")  # fmt: skip


def cart_header(wasm: Path, cart: dict[str, tuple[str, list[str]]]) -> str:
    tag = wasm.stem.removeprefix("demo-")
    high = wasm_info.high_water(wasm.read_bytes()) or 0
    return cart_mirror(cart) + f"""/* ZM_CART_VERSION: the table version this cart needs (a mismatch test builds another). */
#ifndef ZM_CART_VERSION
#define ZM_CART_VERSION ZM_SYS_ABI_VERSION
#endif
extern char __cart_bss_start[], __cart_bss_end[]; /* cycles/cart.ld */
static void c_bind(const zm_sys_table* t) {{ zm_sys = t; }}
static void c_instantiate(w2c_cart* c, struct w2c_env* e) {{
    g_cart = c;
    wasm2c_cart_instantiate(c, e);
    c_audio_mirror(c, e);
}}
__attribute__((section(".zm_cart_hdr"), used)) const zm_cart_hdr zm_cart_header = {{
    .magic = ZM_CART_HDR_MAGIC, .version = ZM_CART_VERSION, .hdr_bytes = sizeof(zm_cart_hdr),
    .bss_start = __cart_bss_start, .bss_end = __cart_bss_end, .pages = {pages()}u, .cart_high = {high:#x}u,
    .inst_bytes = sizeof(w2c_cart), .bind = c_bind, .instantiate = c_instantiate, .boot = w2c_cart_boot,
    .skip_boot = w2c_cart_skipBoot, .frame = w2c_cart_frame, .plane_enabled = w2c_cart_isPlaneEnabled,
    .hbl_dispatch = w2c_cart_hblDispatch, .songs = &host_songs, .input = &host_input, .dapp = &host_dapp,
    .exports = host_exports, .song_files = zm_songs, .tag = "{tag[:15]}",
}};
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("kind", choices=["system", "cart"])
    ap.add_argument("out", type=Path, help="system: the sys_env.c to write; cart: build/host/<tag> (holds cart.h)")
    ap.add_argument("--cart", type=Path, help="the cart's .wasm (cart)")
    a = ap.parse_args()
    if a.kind == "system":
        system_env(a.out)
    elif a.cart is None:
        ap.error("cart needs --cart")
    else:
        cart_env(a.out, a.cart)


if __name__ == "__main__":
    main()
