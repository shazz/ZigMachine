"""Write the CSR addresses the cycles firmware uses (fpga/cycles/board.h) from
the cycles SoC's csr.json, so no address is retyped by hand.

    uv run python tools/cycles_csr.py build/soc_cycles/csr.json build/cycles/gen/csr_addr.h
    uv run python tools/cycles_csr.py --video build/soc_video/csr.json build/vcycles/gen/csr_addr.h

`--video`: the video sim's SoC (soc/video_sim.py), with the video pipeline's
registers, their fields and the read-back window too (fpga/cycles/vboard.h).

`--hp`: the board's SoC as soc/hp_sim.py simulates it (cycles/board.mk), where
the pipeline's CSRs are `video_*` and the glass reports the firmware's state;
`--hp-check <z7 csr.json>` then refuses a bitstream whose CSR map differs from
the sim's on any register both have (the image is linked for one map):

    uv run python tools/cycles_csr.py --hp build/soc_hp/csr.json build/hcycles/gen/csr_addr.h \
        --hp-check build/soc_z7/csr.json

LiteX's own generated/csr.h would do, but it pulls in LiteX's libbase headers
(system.h, hw/common.h), which this firmware does not build.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

# The registers the firmware touches. zm_cycles_* must stay in soc/zm_cycles.py
# COUNTERS order: board_counters() reads them as one array from the first.
NEEDED = [
    "uart_rxtx",
    "uart_txfull",
    "uart_txempty",
    "sim_finish_finish",
    "zm_cycles_cycles",
    "zm_cycles_ibus_ack",
    "zm_cycles_ibus_wait",
    "zm_cycles_dbus_rd",
    "zm_cycles_dbus_wr",
    "zm_cycles_dbus_wait",
]


VIDEO = ["zmv_cmd", "zmv_status", "zmv_vbase", "zmv_fb0", "zmv_fb1", "zmv_swaps", "zmv_frame"]
VIDEO += ["zmv_comp_busy", "zmv_dma_busy"]
VIDEO += [f"main_ram_{n}" for n in ("cpu_rd", "cpu_wr", "dma_rd", "dma_wr", "both")]


HP_VIDEO = ["cmd", "status", "vbase", "fb0", "fb1", "swaps", "frame", "comp_busy", "dma_busy", "hp_cfg", "hp_probe_probe"]
# Registers only a debug build has (soc/zm_z7.py --hp-probe): no #define without them, and the
# firmware (cycles/bdiag.c) leaves the probe out.
HP_OPTIONAL = {"video_hp_probe_probe"}
HP_GLASS = ["glass_cart_state", "glass_cart_beat"]
# The input the glass hands the cart (soc/zm_glass.py; cycles/binput.c reads them).
HP_GLASS += [f"glass_{n}" for n in ("key_data", "key_valid", "key_pop", "joy", "pointer", "pointer_ack")]


def hp_header(csr: dict[str, dict[str, Any]]) -> str:
    """--hp: the names the firmware uses (CSR_ZMV_*) for the board SoC's video_* registers."""
    regs = csr["csr_registers"]
    names = {n: n for n in NEEDED + HP_GLASS} | {f"zmv_{v}": f"video_{v}" for v in HP_VIDEO}
    names = {n: src for n, src in names.items() if src in regs or src not in HP_OPTIONAL}
    missing = [src for src in names.values() if src not in regs]
    if missing:
        sys.exit(f"cycles_csr: the SoC has no {missing}; is it soc/hp_sim.py's?")
    lines = ["/* Generated by fpga/tools/cycles_csr.py --hp from csr.json: do not edit. */"]
    lines += ["#ifndef ZM_CSR_ADDR_H", "#define ZM_CSR_ADDR_H"]
    lines += [f"#define CSR_{n.upper()}_ADDR 0x{regs[src]['addr']:08x}u" for n, src in names.items()]
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from soc.zm_video_csr import CMD_FIELDS, STATUS_FIELDS

    lines += [f"#define ZMV_WINDOW_ADDR 0x{csr['memories']['zm_video']['base']:08x}u"]
    if "zm_blit" in csr["memories"]:  # the blitter's M-only window (soc/zm_blit_soc.py, cycles/bblit.c)
        lines += [f"#define ZMB_WINDOW_ADDR 0x{csr['memories']['zm_blit']['base']:08x}u"]
    lines += [*fields("CMD", CMD_FIELDS), *fields("STATUS", STATUS_FIELDS)]
    return "\n".join([*lines, "#endif", ""])


def hp_check(sim: dict[str, dict[str, Any]], board: dict[str, dict[str, Any]], need_blit: bool = False) -> None:
    """The bitstream's map must give every register the firmware uses the sim's address."""
    used = [*NEEDED, *HP_GLASS, *(f"video_{v}" for v in HP_VIDEO)]
    s, b = sim["csr_registers"], board["csr_registers"]
    bad = [n for n in used if n in b and n in s and b[n]["addr"] != s[n]["addr"]]
    bad += [n for n in used if n not in b and n not in HP_OPTIONAL and not n.startswith(("sim_finish", "uart_"))]
    bad += [n for n in HP_OPTIONAL if (n in b) != (n in s)]  # a probe in one map only moves what follows it
    if sim["memories"]["zm_video"] != board["memories"]["zm_video"]:
        bad.append("zm_video window")
    # An image built for the blitter (--need-blit) runs only on a bitstream that has it, at the sim's address.
    if (need_blit or "zm_blit" in board["memories"]) and sim["memories"].get("zm_blit") != board["memories"].get(
        "zm_blit"
    ):
        bad.append("zm_blit window (build the bitstream with --blit, or the image with ZM_BLIT=sw)")
    if bad:
        sys.exit(f"cycles_csr: the board's CSR map differs from soc/hp_sim.py's on {bad}")


def fields(prefix: str, spec: list[tuple[str, int, str]]) -> list[str]:
    """#defines of each field's shift and mask, from soc/zm_video_pipe.py's lists."""
    out, at = [], 0
    for name, width, _ in spec:
        out += [
            f"#define ZMV_{prefix}_{name.upper()}_SHIFT {at}u",
            f"#define ZMV_{prefix}_{name.upper()}_MASK 0x{(1 << width) - 1:x}u",
        ]
        at += width
    return out


def video_lines(csr: dict[str, dict[str, Any]]) -> list[str]:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from soc.zm_video_csr import CMD_FIELDS, STATUS_FIELDS

    window = csr["memories"]["zmv_window"]["base"]
    return [f"#define ZMV_WINDOW_ADDR 0x{window:08x}u", *fields("CMD", CMD_FIELDS), *fields("STATUS", STATUS_FIELDS)]


def header(csr: dict[str, dict[str, Any]], video: bool = False) -> str:
    regs = csr["csr_registers"]
    needed = NEEDED + (VIDEO if video else [])
    missing = [n for n in needed if n not in regs]
    if missing:
        sys.exit(f"cycles_csr: the SoC has no {missing}; is it soc/cycles_sim.py's?")
    counters = [regs[n]["addr"] for n in NEEDED if n.startswith("zm_cycles_")]
    if counters != list(range(counters[0], counters[0] + 4 * len(counters), 4)):
        sys.exit(f"cycles_csr: ZMCycles counters are not one contiguous array: {counters}")
    lines = ["/* Generated by fpga/tools/cycles_csr.py from csr.json: do not edit. */"]
    lines += ["#ifndef ZM_CSR_ADDR_H", "#define ZM_CSR_ADDR_H"]
    lines += [f"#define CSR_{n.upper()}_ADDR 0x{regs[n]['addr']:08x}u" for n in needed]
    if video:
        lines += video_lines(csr)
    return "\n".join([*lines, "#endif", ""])


def main() -> None:
    args = sys.argv[1:]
    if args and args[0] == "--hp":
        sim = json.loads(Path(args[1]).read_text())
        if "--hp-check" in args:
            hp_check(sim, json.loads(Path(args[args.index("--hp-check") + 1]).read_text()), "--need-blit" in args)
        Path(args[2]).parent.mkdir(parents=True, exist_ok=True)
        Path(args[2]).write_text(hp_header(sim))
        return
    video = "--video" in args
    args = [a for a in args if a != "--video"]
    src, dst = Path(args[0]), Path(args[1])
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(header(json.loads(src.read_text()), video))


if __name__ == "__main__":
    main()
