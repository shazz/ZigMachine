"""The board's split images as files (decisions.md 2026-10-15): the lean cart's header, the
SD card's system file (system.rv32, before ZX0), and where the pair puts the disk. Used by
the sim's DDR image (tools/ddr_init.py --cart) and the card's shelf (tools/glass_shelf.py);
glass reads the same bytes in Zig (glass/src/system.zig). map_cart.zig holds every number.
"""

from __future__ import annotations

import struct
import sys
from dataclasses import dataclass
from pathlib import Path

FPGA = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(FPGA / "gen"))
import glass_cart  # generated by make memmap
import glass_map

MASK = 0xFFFF_FFFF


class SplitError(ValueError):
    """A system or cart image that the glass would refuse."""


def u32(b: bytes, at: int) -> int:
    return struct.unpack_from("<I", b, at)[0]


def vtext(v: int) -> str:
    return f"{v >> 16}.{v & 0xFFFF}"


def abi_ok(need: int, have: int) -> bool:
    """cycles/bsys_abi.h's rule: the same major, the cart's minor at most the system's."""
    return need >> 16 == have >> 16 and need & 0xFFFF <= have & 0xFFFF


@dataclass(frozen=True)
class CartHeader:
    version: int  # the table version the cart needs
    bss_end: int  # window offset: the disk may start here


def is_cart(image: bytes) -> bool:
    return len(image) >= 4 and u32(image, 0) == glass_cart.CART_HDR_MAGIC


def cart_header(image: bytes) -> CartHeader:
    if len(image) < glass_cart.CART_HDR_BSS_END_AT + 4 or not is_cart(image):
        raise SplitError("not a lean cart image: no ZMCA header at its start")
    end = u32(image, glass_cart.CART_HDR_BSS_END_AT) - glass_map.CART_CPU_BASE
    if not glass_cart.CART_IMG_AT + len(image) <= end <= glass_map.DISK_END:
        raise SplitError(f"the cart's .bss end {end:#x} is not past its {len(image)} B image or is past the pictures")
    return CartHeader(u32(image, glass_cart.CART_HDR_VERSION_AT), end)


def table_version(system: bytes, count: int | None = None) -> int:
    """The version in the system image's own table (zm_sys_table: magic, version, count)."""
    magic = struct.pack("<I", glass_cart.SYS_MAGIC)
    hits = [i for i in range(0, len(system) - 12, 4) if system[i : i + 4] == magic]
    hits = [i for i in hits if count is None or u32(system, i + 8) == count]
    if len(hits) != 1:
        raise SplitError(f"the system image holds {len(hits)} tables, not one")
    return u32(system, hits[0] + 4)


def sys_file(system: bytes, version: int) -> bytes:
    """The card's system.rv32 before packing: the four-word head, then the image."""
    if len(system) > glass_cart.CART_IMG_AT:
        raise SplitError(f"a {len(system)} B system image runs into the cart at {glass_cart.CART_IMG_AT:#x}")
    n = len(system)
    return struct.pack("<4I", glass_cart.SYS_MAGIC, version, n, ~(glass_cart.SYS_MAGIC ^ version ^ n) & MASK) + system


def sys_unfile(data: bytes) -> tuple[int, bytes]:
    """(version, image) of a depacked system.rv32; SplitError if the head does not check."""
    head = glass_cart.SYS_HEAD_WORDS * 4
    if len(data) < head:
        raise SplitError("the system file is shorter than its head")
    magic, version, n, chk = struct.unpack_from("<4I", data)
    if magic != glass_cart.SYS_MAGIC or chk != ~(magic ^ version ^ n) & MASK or n != len(data) - head:
        raise SplitError("the system file's head does not check")
    if n > glass_cart.CART_IMG_AT:
        raise SplitError("the system image runs into the cart")
    return version, data[head:]


def check_pair(system_version: int, cart: bytes) -> CartHeader:
    """The cart's header, if this system runs it; SplitError naming both versions if not."""
    h = cart_header(cart)
    if not abi_ok(h.version, system_version):
        raise SplitError(f"the cart needs system table {vtext(h.version)}, the system has {vtext(system_version)}")
    return h
