"""The board SoC sim's DDR image (soc/zm_simaxi.py reads it with $readmemh): the board
image at the cart window's start and, when the cart has a shelf disk, that disk and its
descriptor where ZWINDOW's loader puts them (fpga/glass/src/loader.zig `plan`; map.zig,
"the disk in the cart window"), so ZIGGY's drive (cycles/bdisk.c) finds what it finds on
the board.

    uv run python tools/ddr_init.py build/hcycles/sim/<tag>/fw.bin OUT.init [--disk ../docs/demo-<tag>.zmd] [--program]
    uv run python tools/ddr_init.py <split>/sim_snd/sys.bin OUT.init --cart <split>/carts/<tag>/cart.bin [--disk ...]

--disk takes the SHELF disk (docs/), the one the browser mounts and the glass rebuilds
from the fat disk. One little-endian 64-bit word a line, as `od -An -v -tx8 -w8` writes
it. The disk and the descriptor start at their own word addresses (`@hex` lines), so the
file holds what is placed, not the 32 MiB window's zeros.
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

FPGA = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(FPGA / "gen"))
import glass_cart  # generated by make memmap
import glass_map

sys.path.insert(0, str(FPGA / "tools"))
import split_image  # after the path insert

WINDOW = glass_map.DDR_CART_BYTES  # soc/zm_hp.py WINDOW: the sim's DDR is the cart window


def disk_at(image_len: int, disk_len: int, window: int = WINDOW) -> int:
    """loader.zig diskAt: the first DISK_ALIGN boundary after the image, ending by the
    pictures and below the descriptor."""
    at = -(-image_len // glass_map.DISK_ALIGN) * glass_map.DISK_ALIGN
    if at + disk_len > min(glass_map.DISK_END, window - glass_map.DISK_DESC_FROM_TOP):
        raise SystemExit(f"ddr_init: a {disk_len} B disk after a {image_len} B image passes the pictures")
    return at


def descriptor(at: int, size: int, magic: int = glass_map.DISK_MAGIC) -> bytes:
    """map.zig's four words; `magic` DISK_MAGIC_PROGRAM (map_cart.zig) for a program off the disk."""
    return struct.pack("<4I", magic, at, size, ~(magic ^ at ^ size) & 0xFFFF_FFFF)


def words(data: bytes) -> list[str]:
    data += bytes(-len(data) % 8)
    return [f"{int.from_bytes(data[i : i + 8], 'little'):016x}" for i in range(0, len(data), 8)]


def init_lines(
    image: bytes, disk: bytes | None, magic: int = glass_map.DISK_MAGIC, cart: bytes | None = None
) -> list[str]:
    """The image at 0; a lean `cart` at CART_IMG_AT (image = the system, decisions.md 2026-10-15),
    the disk then after the cart's .bss; the disk and its descriptor."""
    lines, end = words(image), len(image)
    if cart is not None:
        split_image.sys_file(image, 0)  # refuses a system that runs into the cart
        end = split_image.cart_header(cart).bss_end
        lines += [f"@{glass_cart.CART_IMG_AT // 8:x}", *words(cart)]
    if disk is not None:
        at = disk_at(end, len(disk))
        desc_at = WINDOW - glass_map.DISK_DESC_FROM_TOP
        lines += [f"@{at // 8:x}", *words(disk), f"@{desc_at // 8:x}", *words(descriptor(at, len(disk), magic))]
    return lines


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("image", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--disk", type=Path)
    ap.add_argument("--program", action="store_true", help="the cart is a program launched off the disk")
    ap.add_argument("--cart", type=Path, help="a lean cart image: `image` is then the system image")
    a = ap.parse_args()
    disk = a.disk.read_bytes() if a.disk else None
    magic = glass_cart.DISK_MAGIC_PROGRAM if a.program else glass_map.DISK_MAGIC
    cart = a.cart.read_bytes() if a.cart else None
    a.out.write_text("\n".join(init_lines(a.image.read_bytes(), disk, magic, cart)) + "\n")


if __name__ == "__main__":
    main()
