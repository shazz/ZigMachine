// --------------------------------------------------------------------------
// The VHS OSD: when a cart boots, the deck prints its name over the picture for
// a few seconds — greenish phosphor, odd scanlines only, never quite still.
//
// Host-side only. This is the GLASS, not the hardware: the sealed machine knows
// nothing about it and no cart can ask for it. A classic script loaded after
// sealed-loader.js, whose top-level state (demo, channels, loadChannels) it
// shares, exactly as upload-cart.js does.
//
// The name and the machine come from docs/channels.json — {tag, title, type}
// records generated by tools/channels.py out of apps/zig/scenes/catalog.zig — so
// adding a screen needs no edit here. A cart with no catalog entry (an upload,
// ?demo=) falls back to its tag, which is what it was called anyway.
// --------------------------------------------------------------------------
const OSD_HOLD_MS = 3400; // how long the card holds before it fades out

let osdPending = null; // a booting cart's card, shown once that cart is RUNNING
let osdTimer = null;

// The catalog's title + machine for a tag; the tag, tidied, when it has none.
// Never blocks or fails a boot: no channel list at all simply means tags.
async function cartOsdCard(tag) {
    const list = (typeof loadChannels === "function") ? await loadChannels() : null;
    const hit = list && list.find((c) => c.tag === tag);
    if (hit) return { title: hit.title, type: hit.type };
    return { title: String(tag).replace(/\.(wasm|zmd)$/i, "").replace(/[_-]+/g, " "), type: "" };
}

// Paint a card on the glass NOW. Console-callable for a look:
//   showCartOsd("SILENTS HYBRID GLENZ", "amiga")
function showCartOsd(title, type) {
    const el = document.getElementById("cart_osd");
    if (!el) return;
    el.textContent = "";
    const name = document.createElement("span");
    name.className = "cart_osd_name";
    name.textContent = title;
    el.appendChild(name);
    // "unknown" is the catalog's honest answer for a screen nobody has traced;
    // the deck says nothing rather than printing it.
    if (type && type !== "unknown") {
        const kind = document.createElement("span");
        kind.className = "cart_osd_type";
        kind.textContent = type;
        el.appendChild(kind);
    }
    el.classList.remove("on");
    void el.offsetWidth; // reflow: the shake restarts from its first frame
    el.classList.add("on");
    if (osdTimer) clearTimeout(osdTimer);
    osdTimer = setTimeout(() => el.classList.remove("on"), OSD_HOLD_MS);
}

// A cart is booting: remember its card, don't show it yet. A channel change
// arrives through TV snow and a power-on through the boot ROM, and a deck prints
// the title over the PICTURE, not over either of those.
function armCartOsd(tag) {
    // The desktop is the OS, not a cart; the menu (a null tag) names nothing.
    if (!tag || tag === "gem") { osdPending = null; return; }
    cartOsdCard(tag).then((card) => { osdPending = card; });
}

// Called by the render loop each frame: fire the armed card once the cart says
// it is running (demo_main.zig isBooted), or at once for an older cart that
// cannot say.
function pollCartOsd() {
    if (!osdPending) return;
    if (typeof demo !== "undefined" && demo && demo.isBooted && !demo.isBooted()) return;
    showCartOsd(osdPending.title, osdPending.type);
    osdPending = null;
}

// The tag behind a disk URL ("demo-tsl_hybridglenz.zmd" -> "tsl_hybridglenz"),
// so ?disk= names its cart too. Null when the URL is not one of ours.
function osdTagFromDiskUrl(url) {
    const m = /(?:^|\/)demo-(.+)\.zmd$/.exec(url || "");
    return m ? m[1] : null;
}

window.showCartOsd = showCartOsd;
