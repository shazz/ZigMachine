"""cart_data.py <unpacked.prg> <outdir>: the static data Mind Rewind's cart embeds, cut from the depacked
PRG (offsets TEXT-relative = PRG file offset - 28). Only data that is IN the binary (art, tables,
palettes, text); the buffers the demo generates at start-up are generated by the cart too
(stripes_gen.zig, rainbow_gen.zig), never ripped."""
import struct
import sys
from pathlib import Path

BANK = 0x7C624  # the stripe bank (BSS); the 128-row workspace sits right before it
ROW = 208

prg = Path(sys.argv[1]).read_bytes()[28:]
out = Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)


def cut(name: str, off: int, n: int) -> None:
    (out / name).write_bytes(prg[off:off + n])


def longs(off: int, n: int) -> list[int]:
    return [struct.unpack('>I', prg[off + 4 * i:off + 4 * i + 4])[0] for i in range(n)]


cut('stripe_patterns.bin', 0x317C - 15 * 16, 16 * 16)  # pass p uses $317C - 16p
cut('sin_208c.bin', 0x208C, 2048)  # part A: 0..511 offsets
cut('tab_288c.bin', 0x288C, 2048)  # part A: 0..31 offsets
cut('sin_271c8.bin', 0x271C8, 2560)  # rainbow generator: sin x 32767, 1024 a turn (+256)
cut('sin_b61a.bin', 0xB61A, 1024)  # picture wobble: sin x 16384, 512 a turn
cut('flip_3e496.bin', 0x3E496, 90 * 400)  # picture flip: 90 frames x 200 line offsets
cut('wobble_script.bin', 0xBA2A, 9 * 6 + 2)  # (speed, limit, amplitude) x 9, then -1
cut('girl.pal', 0x31756, 32)
cut('girl.bin', 0x31776, 32000)
cut('rg_end.pal', 0x27BD4, 32)
cut('rg_end.bin', 0x27BF4, 32000)
cut('band.pal', 0x17082, 32)
cut('band.bin', 0x170A2, 42 * 160)
cut('pal_stripes.pal', 0x3912, 32)
cut('pal_rainbow.pal', 0x2F934, 32)
cut('pal_scroller.pal', 0xC59A, 32)
cut('bars.bin', 0x38D6, 0x38F8 - 0x38D6 + 28)  # the 14-line window slides over these words
# line pointer tables -> row index in [workspace 128 | bank 512] and byte column
for name, off, n in (('lines_41a4.bin', 0x41A4, 64), ('lines_42a4.bin', 0x42A4, 128)):
    rows = []
    for v in longs(off, n):
        rel = v - BANK + 128 * ROW
        assert rel % ROW == 8, hex(v)
        rows.append(rel // ROW)
    (out / name).write_bytes(b''.join(struct.pack('<H', r) for r in rows))
# scroller font: char -> byte offset of its first column in the font block
ptrs = longs(0xC42E, 91)
lo = min(ptrs)
hi = max(ptrs) + 0x480
cut('font.bin', lo, hi - lo)
(out / 'font_ptrs.bin').write_bytes(b''.join(struct.pack('<H', p - lo) for p in ptrs))
end = prg.index(b'\0', 0xC84C)
cut('scrolltext.bin', 0xC5D6, end + 1 - 0xC5D6)  # leading and trailing 0: both directions stop there
print(f'font {hi - lo} bytes, text {end + 1 - 0xC5D6} bytes')
