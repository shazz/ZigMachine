"""music_blocks.py <unpacked.prg> <outdir>: cut Mind Rewind's DMA music out of the depacked PRG for
apps/zig/assets/screens/mindwind/mw_music.s (offsets are TEXT-relative = PRG file offset - 28).

  mw_code.bin   $75FE-$8ACC  the sequencer, its voices, DMA buffers and init (self-contained: every
                             branch and (pc) reference stays inside; 13 absolute longs leave it)
  mw_data.bin   $1EDC2-$271C8 the music-on flag, sample table, samples (unsigned), songs 1 and 2
  mw_sfx.bin    $47136-$4B4CE the tape-rewind one-shot (signed, 12517 Hz mono)
  mw_reloc.i    one `dc.w offset` + `dc.l target-sndh` pair per absolute long in mw_code.bin, so the
                SNDH's init can add its load address (the PRG's own relocation table, filtered)"""
import struct
import sys
from pathlib import Path

CODE = (0x75FE, 0x8ACC)
DATA = (0x1EDC2, 0x271C8)
SFX = (0x47136, 0x4B4CE)
STEPS = 0x4B4DC  # BSS: 64 pitches x 256 step words, built by the init ($88C4)
BUFP = 0x59C  # two longs: the buffer being mixed, the buffer DMA plays (swapped each frame)


def relocs(prg_file: bytes, text: bytes) -> list[int]:
    _, t, da, _, s = struct.unpack('>HIIII', prg_file[:18])
    r = 28 + t + da + s
    off = struct.unpack('>I', prg_file[r:r + 4])[0]
    out = [off]
    i = r + 4
    while prg_file[i]:
        off += 254 if prg_file[i] == 1 else prg_file[i]
        if prg_file[i] != 1:
            out.append(off)
        i += 1
    return out


def target_expr(t: int) -> str:
    if CODE[0] <= t < CODE[1]:
        return f'mcode+${t - CODE[0]:X}'
    if DATA[0] <= t < DATA[1]:
        return f'mdata+${t - DATA[0]:X}'
    if t == STEPS:
        return 'steps'
    if t == BUFP:
        return 'bufp'
    raise SystemExit(f'unmapped relocation target ${t:X}')


def main() -> None:
    raw = Path(sys.argv[1]).read_bytes()
    text = raw[28:]
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    (out / 'mw_code.bin').write_bytes(text[CODE[0]:CODE[1]])
    (out / 'mw_data.bin').write_bytes(text[DATA[0]:DATA[1]])
    (out / 'mw_sfx.bin').write_bytes(text[SFX[0]:SFX[1]])
    lines = ['; generated by prototypes/mindwind_re/scripts/music_blocks.py: offset in mw_code.bin, target']
    n = 0
    for r in relocs(raw, text):
        if CODE[0] <= r < CODE[1]:
            t = struct.unpack('>I', text[r:r + 4])[0]
            lines.append(f'\tdc.w\t${r - CODE[0]:X}\n\tdc.l\t{target_expr(t)}-sndh')
            n += 1
    lines.append(f'NRELOC\tequ\t{n}')
    (out / 'mw_reloc.i').write_text('\n'.join(lines) + '\n')
    print(f'{n} relocations')


if __name__ == '__main__':
    main()
