// --------------------------------------------------------------------------
// gen_anima: the build-time generator of everything ANIMA draws from tables.
//
//   gen_anima <font16.raw> <out dir>
//
// build.zig runs it on the HOST and hands the carts <out dir>/anima_art.zig as
// the module "anima_art" (it @embedFile's the .bin files beside it). Each
// builder lives next to the part that uses it: art.zig (logo, font),
// gen_tunnel.zig. Deterministic: the same inputs give the same bytes.
// Adding a table needs no build.zig change: write it here and list it in ART.
// --------------------------------------------------------------------------
const std = @import("std");
const art = @import("art.zig");
const gen = @import("gen.zig");
const tun = @import("gen_tunnel.zig");

var logo: [art.LH * art.LW]u8 = undefined;
var strip: [art.CELL_H * art.STRIP_W]u8 = undefined;
var map: [tun.VW * tun.HALF]u16 = undefined;
var tex: [tun.TEX_N * tun.TEX_N]u8 = undefined;

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    var args = init.minimal.args.iterate();
    _ = args.next();
    const font_path = args.next() orelse return error.Usage;
    const out_path = args.next() orelse return error.Usage;
    const cwd = std.Io.Dir.cwd();
    const font = try cwd.readFileAlloc(io, font_path, init.arena.allocator(), .limited(1 << 16));
    if (font.len != gen.SHEET_BYTES) return error.FontSize;
    const sheet = font[0..gen.SHEET_BYTES];

    art.buildLogo(sheet, &logo);
    art.buildFont(sheet, &strip);
    tun.buildMap(&map);
    tun.buildTex(&tex);

    const files = [_]struct { name: []const u8, data: []const u8 }{
        .{ .name = "logo", .data = &logo },
        .{ .name = "font", .data = &strip },
        .{ .name = "tunnel_map", .data = std.mem.sliceAsBytes(&map) },
        .{ .name = "tunnel_tex", .data = &tex },
    };
    try cwd.createDirPath(io, out_path);
    const dir = try cwd.openDir(io, out_path, .{});
    var zig: std.ArrayList(u8) = .empty;
    const a = init.arena.allocator();
    try zig.appendSlice(a, "// Generated by apps/zig/scenes/anima/gen_anima.zig at build time.\n");
    for (files) |f| {
        const bin = try std.fmt.allocPrint(a, "{s}.bin", .{f.name});
        try dir.writeFile(io, .{ .sub_path = bin, .data = f.data });
        try zig.appendSlice(a, try std.fmt.allocPrint(a, "pub const {s} align(4) = @embedFile(\"{s}\").*;\n", .{ f.name, bin }));
    }
    try dir.writeFile(io, .{ .sub_path = "anima_art.zig", .data = zig.items });
}
