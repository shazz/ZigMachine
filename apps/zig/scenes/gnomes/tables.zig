// --- ST register word -> the palette's RGBA (machine/beam.zig stToRgba) ----
// MUST stay in sync with the machine: nibble 0 (bits 3..0) = blue, 1 = green,
// 2 = red, gun = ((n & 7) << 1 | (n >> 3) & 1) * 16. No other coefficients.
fn gun(nibble: u16) u32 {
    const level: u32 = ((nibble & 7) << 1) | ((nibble >> 3) & 1);
    return level * 16;
}

pub fn st(word: u16) u32 {
    return 0xFF00_0000 | (gun(word) << 16) | (gun(word >> 4) << 8) | gun(word >> 8);
}

/// The rainbow decoded once, at comptime: the per-frame roll only copies.
pub const RAINBOW_RGBA: [RAINBOW.len]u32 = blk: {
    var out: [RAINBOW.len]u32 = undefined;
    for (RAINBOW, 0..) |w, i| out[i] = st(w);
    break :blk out;
};
