#!/usr/bin/env python3
"""A binary as a C array, the way SID-Wizard's own resources/tools/bin2array writes it (upstream's Makefile
makes resources/*.h with it; they are not in the source archive): `static const unsigned char NAME[] = {...};`
with one closing 0 appended when --nul is given (upstream's code reads `sizeof(NAME)-1` for those).
    bin2h.py <in> <out.h> <NAME> [--nul]"""
import sys

src, dst, name = sys.argv[1:4]
data = open(src, "rb").read() + (b"\0" if "--nul" in sys.argv[4:] else b"")
rows = [",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
with open(dst, "w") as f:
    f.write(f"/* generated by tools/bin2h.py from {src.split('/')[-1]} ({len(data)} bytes) */\n")
    f.write(f"static const unsigned char {name}[] = {{\n" + ",\n".join(rows) + "\n};\n")
