/* kt_tables: the constants klystron computes with libm (and two it hard-codes), printed as Zig, so the
 * BARD .kt player (libs/zig/players/kt_tables_gen.zig) uses upstream's exact numbers with no float
 * per sample. Regenerate with
 *   make -C apps/ports/klystrack/kt_ref tables
 * which writes libs/zig/players/kt_tables_gen.zig. Every value is computed here by the same
 * expression, types and libm as upstream (cyd.c cyd_set_panning, cydrvb.c cydrvb_set_tap, freqs.c). */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#include "snd/cyd.h"
#include "snd/cydrvb.h"
#include "snd/freqs.h"
#include "kestrel_sine.h" /* ../kestrel_sine.h: the cart's integer chorus sine */

/* cyd_set_panning / cydrvb_set_tap's angle: a float, from a double expression. */
static double angle(int panning) {
    float a = M_PI / 2 * (float)(panning - CYD_PAN_LEFT) / (CYD_PAN_RIGHT - CYD_PAN_LEFT);
    return a;
}

/* music.c defines GENERATE_VIBRATO_TABLES, so mus_init_engine fills both LFO tables at run time: the
 * sine from a float sin(), the "random" shape from the first 128 rand() of the process (glibc's, seed 1:
 * klystrack on Linux, and kt_ref, which calls nothing else before). The klystrack cart's wasi-libc rand()
 * gives another table: only the random LFO shape (MUS_SHAPE_RANDOM) differs; no bundled song uses it. */
static void vibrato_tables(void) {
    signed char sine[128], rnd[128];
    for (int i = 0; i < 128; ++i) {
        sine[i] = sin((float)i / 128 * M_PI * 2) * 127;
        rnd[i] = rand();
    }
    printf("\n/// music.c mus_init_engine (GENERATE_VIBRATO_TABLES): sin((float)i / 128 * M_PI * 2) * 127.\n");
    printf("pub const sine_table = [128]i8{\n");
    for (int i = 0; i < 128; i++) printf("%s%d,%s", i % 16 ? " " : "    ", sine[i], i % 16 == 15 ? "\n" : "");
    printf("};\n/// ...and rand(), as glibc's first 128 values from seed 1 (a Sint8 each).\n");
    printf("pub const rnd_table = [128]i8{\n");
    for (int i = 0; i < 128; i++) printf("%s%d,%s", i % 16 ? " " : "    ", rnd[i], i % 16 == 15 ? "\n" : "");
    printf("};\n");
}

int main(void) {
    printf("// GENERATED by apps/ports/klystrack/kt_ref/kt_tables.c (make -C apps/ports/klystrack/kt_ref tables)\n");
    printf("// from upstream klystron at the pinned commit: do not edit.\n\n");
    printf("/// freqs.c frequency_table: (Uint16)(Hz * 16), a semitone a step from C-0.\n");
    printf("pub const frequency = [%d]u16{\n", FREQ_TAB_SIZE);
    for (int i = 0; i < FREQ_TAB_SIZE; i++) printf("%s%u,%s", i % 12 ? " " : "    ", frequency_table[i], i % 12 == 11 ? "\n" : "");
    printf("};\n\n/// cyd_set_panning: (Sint32)(cos(a) * CYD_STEREO_GAIN), (Sint32)(sin(a) * ...), panning 0..128.\n");
    printf("pub const pan_left = [129]i32{\n");
    for (int p = 0; p <= 128; p++) printf("%s%d,%s", p % 16 ? " " : "    ", (Sint32)(cos(angle(p)) * CYD_STEREO_GAIN), p % 16 == 15 ? "\n" : "");
    printf("\n};\npub const pan_right = [129]i32{\n");
    for (int p = 0; p <= 128; p++) printf("%s%d,%s", p % 16 ? " " : "    ", (Sint32)(sin(angle(p)) * CYD_STEREO_GAIN), p % 16 == 15 ? "\n" : "");
    printf("\n};\n\n/// cydrvb_set_tap's cos(a) and sin(a), panning 0..128, as the exact doubles (used at load only).\n");
    printf("pub const rvb_cos = [129]f64{\n");
    for (int p = 0; p <= 128; p++) printf("    %a,\n", cos(angle(p)));
    printf("};\npub const rvb_sin = [129]f64{\n");
    for (int p = 0; p <= 128; p++) printf("    %a,\n", sin(angle(p)));
    printf("};\n\n/// CYDRVB_LOW_LIMIT: a tap at or below this gain (0.01 dB) is off.\n");
    printf("pub const rvb_low_limit: i32 = %d;\n", CYDRVB_LOW_LIMIT);
    printf("/// cydrvb_set_tap: (int)(pow(10.0, gain_db * 0.01) * CYDRVB_0dB) for gain_db = rvb_low_limit + 1 + i.\n");
    printf("pub const rvb_gain = [%d]i32{\n", -CYDRVB_LOW_LIMIT);
    for (int g = CYDRVB_LOW_LIMIT + 1, i = 0; g <= 0; g++, i++)
        printf("%s%d,%s", i % 16 ? " " : "    ", (int)(pow(10.0, (double)g * 0.01) * CYDRVB_0dB), i % 16 == 15 ? "\n" : "");
    printf("\n};\n\n/// kestrel_sine.h: sin(2 pi i / 1024) in Q30, i = 0..1024 (the klystrack cart's integer chorus LUT).\n");
    printf("pub const sine_q30 = [1025]i32{\n");
    for (int i = 0; i <= 1024; i++) printf("%s%d,%s", i % 8 ? " " : "    ", kestrel_sine_q30[i], i % 8 == 7 ? "\n" : "");
    printf("\n};\n");
    vibrato_tables();
    return 0;
}
