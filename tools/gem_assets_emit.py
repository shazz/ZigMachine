"""Write the Zig module gem_assets_conv.py collected (the declarations of
rom/gem/engine/assets_none.zig, filled). The type definitions are copied from that
file, so the stub and every generated module share one definition."""

from __future__ import annotations

from pathlib import Path

from gem_assets_fsel import emit as fsel_emit

STUB = Path(__file__).resolve().parent.parent / "rom/gem/engine/assets_none.zig"


def types() -> str:
    text = STUB.read_text()
    start = text.index("pub const Font = struct")
    end = text.index("\n", text.index("pub const Tree = struct")) + 1
    return text[start:end]


def blob(xs: list[int]) -> str:
    return "&[_]u8{" + ",".join(str(x) for x in xs) + "}"


def zstr(s: str) -> str:
    """A Zig string literal: printable ASCII kept, everything else escaped."""
    if s.startswith('"'):
        return s  # already a Zig literal (zig_extract wrote it)
    out = "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else f"\\x{ord(c) & 0xFF:02x}" for c in s)
    return f'"{out}"'


def font(f) -> str:
    return "null" if f is None else f".{{ .w = {f['w']}, .h = {f['h']}, .data = {blob(f['data'])} }}"


def mouse(m) -> str:
    if m is None:
        return "null"
    words = lambda ws: ".{" + ",".join(f"0x{w:04x}" for w in ws) + "}"
    return f".{{ .mask = {words(m['mask'])}, .data = {words(m['data'])}, .hx = {m['hx']}, .hy = {m['hy']} }}"


def icon(i) -> str:
    col = "null" if i["col"] is None else blob(i["col"])
    return (f".{{ .id = {zstr(i['id'])}, .w = {i['w']}, .h = {i['h']}, .mask = {blob(i['mask'])}, "
            f".data = {blob(i['data'])}, .col = {col} }}")


def obj(o) -> str:
    extra = ""
    if o.get("kind") == 1:
        extra = f", .box = 0x{o['box']:08x}"
    elif o.get("kind") in (2, 4):
        extra = f", .str = {zstr(o['str'])}"
    elif o.get("kind") == 3:
        extra = (f", .str = {zstr(o['str'])}, .font = {o['font']}, .just = {o['just']}, "
                 f".color = 0x{o['color']:04x}, .thick = {o['thick']}")
    return (f".{{ .next = {o['next']}, .head = {o['head']}, .tail = {o['tail']}, .ty = {o['ty']}, "
            f".flags = 0x{o['flags']:04x}, .state = 0x{o['state']:04x}, .x = {o['x']}, .y = {o['y']}, "
            f".w = {o['w']}, .h = {o['h']}, .kind = {o.get('kind', 0)}{extra} }}")


def tree(t) -> str:
    objs = ",\n        ".join(obj(o) for o in t["objs"])
    return f"    .{{ .group = {zstr(t['group'])}, .name = {zstr(t['name'])}, .objs = &[_]Obj{{\n        {objs},\n    }} }},"


def palette(p) -> str:
    if p is None:
        return "null"
    return ".{" + ",".join(".{" + ",".join(str(c) for c in rgb) + "}" for rgb in p) + "}"


def emit(d: dict, src_name: str) -> str:
    pats = ",".join(".{" + ",".join(f"0x{w:04x}" for w in p) + "}" for p in d["patterns"])
    lines = [
        "// GENERATED by tools/gem_assets_conv.py from a LOCAL asset directory. Never commit.",
        "pub const present = true;",
        f"pub const name: []const u8 = {zstr(src_name)};",
        types(),
        f"pub const font_8x16: ?Font = {font(d['fonts'].get('8x16'))};",
        f"pub const font_8x8: ?Font = {font(d['fonts'].get('8x8'))};",
        f"pub const font_6x6: ?Font = {font(d['fonts'].get('6x6'))};",
        f"pub const arrow: ?Mouse = {mouse(d['arrow'])};",
        f"pub const busy: ?Mouse = {mouse(d['busy'])};",
        "pub const icons: []const Icon = &[_]Icon{" + ",".join(icon(i) for i in d["icons"]) + "};",
        "pub const cicons: []const Icon = &[_]Icon{" + ",".join(icon(i) for i in d["cicons"]) + "};",
        "pub const images: []const Icon = &[_]Icon{" + ",".join(icon(i) for i in d.get("images", [])) + "};",
        f"pub const patterns: []const [16]u16 = &[_][16]u16{{{pats}}};",
        f"pub const palette: ?[16][3]u8 = {palette(d['palette'])};",
        "pub const trees: []const Tree = &[_]Tree{",
        *(tree(t) for t in d["trees"]),
        "};",
        fsel_emit(d.get("selectors", [])),
    ]
    return "\n".join(lines) + "\n"
