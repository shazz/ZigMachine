"""Stage 4 of the baker: the files the cart embeds (apps/zig/assets/screens/aurora_boot/) and the reference
hashes the harness checks the cart against.

  sky.zx0        the 565 base picture (photo with its stars painted out, tone-mapped as the lab does), ZX0
  aurora.zx0     the aurora's per-frame delta containers back to back, aurora.idx their u32 offsets
  stars.zx0      the star plane's i16 delta records, one per 30 fps frame
  aurora_meta.zig  the constants the cart compiles against (counts, band, edges, palette)
  aurora_ref.json  the Python reference model: md5 of the TC plane when aurora frame j is fully shown, the
                   baked star pixels at some ticks, and the sizes
"""
import hashlib
import json
from pathlib import Path

import numpy as np

import aurora_pack as pk
from aurora_common import H, W
from aurora_stars import LEVELS, Q4


def plane_after(base_q, pal_words, idx_acc, r0, step):
    """The reference TC plane (H, W) u16 with aurora frame `idx_acc` (stored rows, W) added: the cart's loop in numpy."""
    plane = ((base_q[..., 0].astype(np.uint16) << 11) | (base_q[..., 1].astype(np.uint16) << 5) | base_q[..., 2].astype(np.uint16))
    add = pal_words[idx_acc].astype(np.uint16)
    rows = np.repeat(add, step, axis=0)[:H - r0]
    out = plane.copy()
    out[r0:r0 + len(rows)] = plane[r0:r0 + len(rows)] + rows  # the baker proved no channel overflows: a plain add
    return out


def meta_source(m):
    edges = ", ".join(f".{{ {a}, {b} }}" for a, b in m["edges"])
    pal = ", ".join(str(int(v)) for v in m["palette"])
    return f"""// Generated by tools/boot/aurora_bake.py: do not edit (re-bake instead, then re-pin the harness).
pub const N_STARS: u32 = {m['n_stars']};
pub const NV: u32 = {m['nv']};
pub const REC: u32 = {m['rec']}; // i16 per star-plane record: sx[N] sy[N] lv[N] vx[NV] vy[NV] line word fade
pub const STAR_FRAMES: u32 = {m['star_frames']}; // 30 fps records
pub const Q4: i32 = {Q4};
pub const LEVELS: u32 = {LEVELS};
pub const SAMPLE_RATE: u32 = {m['sample_rate']};
pub const SAMPLE_LEN: u32 = {m['sample_len']};
pub const AURORA_FRAMES: u32 = {m['aurora_frames']};
pub const AURORA_AT: u32 = {m['aurora_at']}; // the star record at which aurora frame 0 shows
pub const BAND_Y0: u32 = {m['band_y0']};
pub const BAND_ROWS: u32 = {m['band_rows']}; // stored rows; each shows on {m['row_step']} screen rows
pub const ROW_STEP: u32 = {m['row_step']};
pub const EDGES = [_][2]u8{{ {edges} }};
pub const PALETTE = [256]u16{{ {pal} }};
{m.get('extra', '')}"""


def write_assets(out, files, meta):
    """`files` maps a file name to its bytes; the meta source is written beside them."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (out / name).write_bytes(data)
    (out / "aurora_meta.zig").write_text(meta_source(meta))


def md5(a):
    return hashlib.md5(np.ascontiguousarray(a).tobytes()).hexdigest()


def reference(base_q, pal_words, idx_stored, r0, rec_rows, meta, probes):
    """The reference JSON for a shared-palette set (A..E): TC plane md5 per probed aurora frame, star pixels per probed record."""
    step = meta["row_step"]
    planes = {j: plane_after(base_q, pal_words, idx_stored[j], r0, step) for j in probes["aurora"]}
    sky = plane_after(base_q, pal_words, np.zeros_like(idx_stored[0]), r0, step)
    return reference_planes(planes, sky, rec_rows, meta, probes)


def sky_plane(base_q):
    return ((base_q[..., 0].astype(np.uint16) << 11) | (base_q[..., 1].astype(np.uint16) << 5) | base_q[..., 2].astype(np.uint16))


def reference_planes(planes, sky, rec_rows, meta, probes):
    """The reference JSON from the TC planes (H, W) u16 of the probed aurora frames (F, G build their own)."""
    n = meta["n_stars"]
    stars = {str(i): [[int(rec_rows[i][k]), int(rec_rows[i][n + k])] for k in range(n)] for i in probes["stars"]}
    return dict(planes_md5={str(j): md5(p.astype("<u2")) for j, p in planes.items()}, stars_xy=stars, sky_md5=md5(sky.astype("<u2")),
                sizes=meta["sizes"], aurora_frames=meta["aurora_frames"], width=W, height=H)
