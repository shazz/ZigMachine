"""The baker's last stage: the files the cart embeds (apps/zig/assets/screens/aurora_boot/) and the reference
hashes the harness checks the cart against.

  sky.zx0          the 565 base picture (photo with its stars painted out, tone-mapped as the lab does), ZX0
  aurora.msk       the aurora's change masks + nibble codes, two containers a frame (aurora_mask.py), aurora.idx their u32 offsets
  overlay.bin      the star plane's changed bytes per 60 Hz frame (aurora_overlay.py)
  word.bin         the baked script name (aurora_word.py), drawn into overlay.bin
  boot.raw         the sound, signed 8-bit mono
  aurora_meta.zig  the constants the cart compiles against (counts, band, the beats' levels, the delta codes)
  aurora_ref.json  the Python reference model: md5 of the TC plane when aurora frame j is fully shown, the
                   baked star pixels at some records, plane 1's md5 at some frames, and the sizes
"""
import hashlib
from pathlib import Path

import numpy as np

import aurora_common as ac


def meta_source(m):
    return f"""// Generated by tools/boot/aurora_bake.py: do not edit (re-bake instead; the harness reads aurora_ref.json).
pub const N_STARS: u32 = {m['n_stars']};
pub const STAR_FRAMES: u32 = {m['star_frames']}; // 30 fps records
pub const SAMPLE_RATE: u32 = {m['sample_rate']};
pub const SAMPLE_LEN: u32 = {m['sample_len']};
pub const AURORA_FRAMES: u32 = {m['aurora_frames']};
pub const AURORA_AT: u32 = {m['aurora_at']}; // the star record at which aurora frame 0 shows
pub const BAND_Y0: u32 = {m['band_y0']};
pub const BAND_ROWS: u32 = {m['band_rows']};
{m['extra']}"""


def write_assets(out, files, meta):
    """`files` maps a file name to its bytes; the meta source is written beside them."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (out / name).write_bytes(data)
    (out / "aurora_meta.zig").write_text(meta_source(meta))


def md5(a):
    return hashlib.md5(np.ascontiguousarray(a).tobytes()).hexdigest()


def reference_planes(planes, sky, rec_rows, meta, probes):
    """The reference JSON from the TC planes (H, W) u16 of the probed aurora frames and the probed star records."""
    n = meta["n_stars"]
    stars = {str(i): [[int(rec_rows[i][k]), int(rec_rows[i][n + k])] for k in range(n)] for i in probes["stars"]}
    return dict(planes_md5={str(j): md5(p.astype("<u2")) for j, p in planes.items()}, stars_xy=stars, sky_md5=md5(sky.astype("<u2")),
                sizes=meta["sizes"], aurora_frames=meta["aurora_frames"], width=ac.W, height=ac.H)
