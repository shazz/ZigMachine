# The credit pictures are Pack-Ice streams in DATA; prototypes/falcon_ays_re/png/ holds them
# depacked (320x240, from the 565 words). Credit order (the list at $13FD1E): file offsets.
# Credit 4 (MUSIC, file offset 1,270,360) does not depack with libs/zig/depackers/ice.zig yet.
CREDITS = {
    "credit_1": "ice_1248168.png",
    "credit_2": "ice_1262996.png",
    "credit_3": "ice_1256210.png",
    "credit_4": "ice_1270360.png",
    "credit_5": "ice_1240654.png",
}


def credit(path: Path) -> bytes:
    """320x200 big-endian RGB565 from the depacked picture (its first 200 rows), or nothing."""
    if not path.is_file():
        return b""
    from PIL import Image  # only a rip build needs Pillow

    im = Image.open(path).convert("RGB")
    out = bytearray()
    for y in range(200):
        for x in range(320):
            r, g, b = im.getpixel((x, y))
            out += struct.pack(">H", (r >> 3) << 11 | (g >> 2) << 5 | b >> 3)
    return bytes(out)


def main() -> None:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    prg = (src / "COMFORT_unpacked.PRG").read_bytes()
    if struct.unpack(">H", prg[:2])[0] != 0x601A:
        sys.exit(f"falcon_ays_art: {src}/COMFORT_unpacked.PRG is not a GEMDOS program")
    img = prg[28:]
    out.mkdir(parents=True, exist_ok=True)
    lines = ["// Generated by tools/falcon_ays_art.py from COMFORT_unpacked.PRG (prototypes/falcon_ays_re): do not edit."]
    lines.append(f'pub const marker = "AYS-RIP {hashlib.md5(prg).hexdigest()[:8]}";')
    for name, (off, size) in TABLES.items():
        (out / f"{name}.bin").write_bytes(img[off : off + size])
        lines.append(f'pub const {name}: []const u8 = @embedFile("{name}.bin");')
    for name, png in CREDITS.items():
        (out / f"{name}.bin").write_bytes(credit(src / "png" / png))
        lines.append(f'pub const {name}: []const u8 = @embedFile("{name}.bin");')
    (out / "ays_art.zig").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
