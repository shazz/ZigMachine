"""`.ktrk.json` -> a Lua table (`KTRK = {...}`) the reference harness loads; all numbers are exact 16.16 values.

Only what the physics reads: vertices, faces (flags, vertex ids, border edges), the ground faces of each
32 x 32 tile (key tx + 32 * tz, the engine's voxel id), the racing line, checkpoints and the start grid.
Derived values (normals, border planes, segment lengths) are computed in Lua by the harness, with the
engine's own 16.16 arithmetic, so no Python float leaks into the reference.
"""

from __future__ import annotations

from racer import ktrk
from racer.ktrk import Doc


def _num(n: int, scale: int, digits: int) -> str:
    return f"{n / scale:.{digits}f}"


def _vertex(v: list[int]) -> str:
    return "{" + ",".join(_num(c, ktrk.SCALE, 7) for c in v) + "}"


def _face(face: Doc) -> str:
    ids = ",".join(str(i + 1) for i in face["v"])
    borders = ",".join(str(e) for e in face.get("borders", []))
    return f"{{flags={ktrk.face_flags(face)},v={{{ids}}},borders={{{borders}}}}}"


def _ground(doc: Doc) -> str:
    items = []
    for (tx, tz), faces in sorted(ktrk.tile_faces(doc, ground_only=True).items(), key=lambda kv: (kv[0][1], kv[0][0])):
        items.append(f"[{tx + ktrk.GRID * tz}]={{{','.join(str(f + 1) for f in faces)}}}")
    return "{" + ",".join(items) + "}"


def _grid(entry: Doc) -> str:
    pos = ",".join(_num(c, ktrk.SCALE, 7) for c in entry["pos"])
    return f"{{seg={entry['segment']},pos={{{pos}}},yaw={_num(entry['yaw_q16'], 65536, 16)}}}"


def to_lua(doc: Doc) -> str:
    """The track as Lua source; deterministic (sorted voxels, fixed number formats)."""
    if not doc["racing_line"] or not doc["start_grid"]:
        raise ValueError("a track needs a racing line and a start grid")
    line = ",".join(f"{{{s['l'] + 1},{s['r'] + 1}}}" for s in doc["racing_line"])
    parts = [
        "v={" + ",\n".join(_vertex(v) for v in doc["vertices"]) + "}",
        "f={" + ",\n".join(_face(f) for f in doc["faces"]) + "}",
        "ground=" + _ground(doc),
        "line={" + line + "}",
        "checkpoints={" + ",".join(str(c) for c in doc["checkpoints"]) + "}",
        "grid={" + ",".join(_grid(g) for g in doc["start_grid"]) + "}",
    ]
    return "-- generated by tools/racer/ktrk_lua.py from " + doc["name"] + "\nKTRK={\n" + ",\n".join(parts) + "}\n"
