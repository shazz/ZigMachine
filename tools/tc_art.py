"""Local pictures for the TC TEST cart (apps/zig/scenes/tc_test.zig), RGB565 little-endian.

    uv run --with pillow python tools/tc_art.py <image dir> <out dir>

Run by build.zig only when `-Dtc-art=<dir>` is given (build.sh passes it when ZM_TC_ART is
set): the pictures are the owner's own, not cleared for publication, so the default build and
the gate never see them and docs/demo-tc_test.* stays free of them (apps/tc_test_check.mjs
checks the git-tracked cart for MARKER).

Every file in the directory, sorted by name, becomes one picture:
  - a raw Falcon true-colour dump (big-endian R5 G6 B5): byte-swapped only, so a real Falcon
    picture is byte-exact. The header is found by arithmetic: a file of exactly w*h*2 bytes for
    a known screen size is headerless; else a big-endian (w, h) pair at offset 2..4 (6-byte
    header: Godpaint .GOD) or 12..14 (18-byte header: .TG1 "COKE format.") whose w*h*2 plus
    that header is the file size;
  - anything Pillow opens: each channel's top bits (zg.tc.rgb565), no dither.
A picture larger than 400x280 is cropped about its centre. Unreadable files are skipped, said so.

Writes <out dir>/tc_art.zig (the module the cart imports) and img<N>.565 beside it.
"""
import sys
from pathlib import Path

MARKER = "TC_TEST_LOCAL_ART"  # in every cart built with local pictures, never in a committed one
MAX_W, MAX_H = 400, 280
BUDGET = 1536 * 1024  # bytes of pictures in the cart (the 3 MiB cart window holds the rest)
HEADERLESS = [(320, 200), (384, 240), (320, 240), (400, 280), (640, 400), (384, 480), (768, 480)]
HEADERS = [(6, 2), (18, 12)]  # (header length, offset of the big-endian w, h)
IMAGE_MAGIC = (b"\x89PNG", b"\xff\xd8", b"GIF8", b"BM", b"II*\x00", b"MM\x00*", b"RIFF")


def falcon(data: bytes):
    """(w, h, little-endian 565 bytes) for a raw Falcon dump, or None."""
    n = len(data)
    for w, h in HEADERLESS:
        if n == w * h * 2:
            return w, h, swap(data), "headerless"
    for head, at in HEADERS:
        if n < head:
            continue
        w, h = int.from_bytes(data[at:at + 2], "big"), int.from_bytes(data[at + 2:at + 4], "big")
        if w and h and n == head + w * h * 2:
            return w, h, swap(data[head:]), f"{head}-byte header"
    return None


def swap(be: bytes) -> bytes:
    out = bytearray(be)
    out[0::2], out[1::2] = be[1::2], be[0::2]
    return bytes(out)


def pillow(path: Path):
    from PIL import Image  # only here: a Falcon-only folder needs no Pillow
    src = Image.open(path)
    img = src.convert("RGB")
    w, h = img.size
    rgb = img.tobytes()
    out = bytearray(w * h * 2)
    for i in range(w * h):
        r, g, b = rgb[3 * i], rgb[3 * i + 1], rgb[3 * i + 2]
        v = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        out[2 * i], out[2 * i + 1] = v & 0xFF, v >> 8
    return w, h, bytes(out), f"{src.format or 'image'} via Pillow"


def crop(w: int, h: int, px: bytes):
    cw, ch = min(w, MAX_W), min(h, MAX_H)
    x0, y0 = (w - cw) // 2, (h - ch) // 2
    rows = [px[((y0 + y) * w + x0) * 2:((y0 + y) * w + x0 + cw) * 2] for y in range(ch)]
    return cw, ch, b"".join(rows)


def convert(path: Path):
    data = path.read_bytes()
    got = None if data.startswith(IMAGE_MAGIC) else falcon(data)  # a PNG of exactly 128,000 bytes is still a PNG
    if got is None:
        try:
            got = pillow(path)
        except Exception as e:  # any unreadable file: skip it, say why
            print(f"tc_art: {path.name}: skipped ({e.__class__.__name__}: {e})", file=sys.stderr)
            return None
    w, h, px, how = got
    cw, ch, px = crop(w, h, px)
    print(f"tc_art: {path.name}: {w}x{h}, {how}" + (f", cropped to {cw}x{ch}" if (cw, ch) != (w, h) else ""), file=sys.stderr)
    return cw, ch, px


def main(src: Path, out: Path) -> int:
    out.mkdir(parents=True, exist_ok=True)
    files = sorted(p for p in src.iterdir() if p.is_file() and not p.name.startswith(".")) if src.is_dir() else []
    entries, total = [], 0
    for p in files:
        got = convert(p)
        if got is None:
            continue
        w, h, px = got
        if total + len(px) > BUDGET:
            print(f"tc_art: {p.name}: skipped, over the {BUDGET // 1024} KB budget", file=sys.stderr)
            continue
        total += len(px)
        (out / f"img{len(entries)}.565").write_bytes(px)
        entries.append((w, h))
    zig = ["// Generated by tools/tc_art.py from the owner's local pictures: never commit a cart built with it.",
           f'pub const marker = "{MARKER}";', "pub const Image = struct { w: u16, h: u16, px: []const u8 };",
           "pub const images = [_]Image{"]
    zig += [f'    .{{ .w = {w}, .h = {h}, .px = @embedFile("img{i}.565") }},' for i, (w, h) in enumerate(entries)]
    zig.append("};")
    (out / "tc_art.zig").write_text("\n".join(zig) + "\n")
    print(f"tc_art: {len(entries)} picture(s), {total} bytes, from {src}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sys.exit(main(Path(sys.argv[1]), Path(sys.argv[2])))
