"""Suicide Barbie mix3 -> sb_spike's data: one blob + its layout module.

  python3 -I tools/sb_mix3/convert.py <suicide-barbie checkout> <out dir>

Reads the SHIPPED PSP blobs (ReleaseCandidate/__SCE__SuicideBarbie/BarbieData/mix/mix3/psp,
TBL, MIT) and writes <out>/mix3.bin + <out>/mix3_layout.zig (offsets, counts, palette).
prototypes/ is not in git, so this runs once by hand and both outputs are committed
(apps/zig/assets/screens/sb_spike/); the cart @embedFile's the blob.

Blob (little endian, every section 4-aligned):
  atlas   256 x ROWS u8 (atlas.py)
  keys    per anim node: Key{ t: [3]i16 Q12, q: [4]i16 Q14 (x y z w), pad } 16 B, 30 Hz
  verts   per LOD per item: Vert{ x y z: i16 Q12, nx ny nz: i16 Q14, u: u16 8.8 texels,
          v: u16 atlas row 11.5 } 16 B
  tris    per LOD per item: [3]u16 vertex indices
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import atlas  # noqa: E402
import decimate  # noqa: E402
import read  # noqa: E402

LODS = 4
SMALL = 300
# No Z buffer: the backdrop is always behind, the floor mark (alphaG, flat on y = 0) always
# on it; everything else is sorted by depth a triangle (the original's msk slices 1 and 2).
LAYERS = {'back': 0, 'alphaG': 1}  # items with fewer triangles are kept whole at every LOD


def q(v, bits):
    return max(-32768, min(32767, round(v * (1 << bits))))


def items(sc, psp):
    """The draw items: an actor's mesh subset with its texture (or env map)."""
    out = []
    for a in sc['actors']:
        m = read.mesh(os.path.join(psp, sc['meshes'][a['mesh']]))
        for s, tris in enumerate(m['subsets']):
            mat = a['mats'][s]
            env = mat['diffuse'] == 0xFFFFFFFF
            tex = sc['textures'][mat['env'] if env else mat['diffuse']][:-4]
            out.append(dict(name=a['name'] + ('' if len(m['subsets']) == 1 else '/%d' % s), node=a['name'],
                            tex=tex, env=env, mesh=dict(p=m['p'], uv=m['uv'], n=m['n'], tris=tris)))
    return out


def vert_bytes(verts, base):
    row0, size = base
    b = bytearray()
    for p, uv, n in verts:
        u = round(uv[0] * size * 256) & 0xFFFF
        v = round((row0 + min(max(uv[1], 0.0), 1.0) * (size - 1)) * 32)
        b += struct.pack('<6h2H', *(q(c, 12) for c in p), *(q(c, 14) for c in n), u, v)
    return b


def key_bytes(keys):
    if len(set(keys)) == 1:
        keys = keys[:1]
    b = bytearray()
    for t, rot, _ in keys:
        b += struct.pack('<8h', *(q(c, 12) for c in t), *(q(c, 14) for c in rot), 0)
    return b, len(keys)


def main(src, out):
    psp = os.path.join(src, 'ReleaseCandidate/__SCE__SuicideBarbie/BarbieData/mix/mix3/psp')
    sc = read.scene(os.path.join(psp, 'mix3.msk'))
    texs = {t[:-4]: read.texture(os.path.join(psp, t)) for t in sc['textures']}
    atl, palette, bases = atlas.build(texs)
    blob = bytearray(atl)
    anim = read.anim(os.path.join(psp, 'mix3.man'))
    nodes = [n for n in anim if n != 'RootNode']
    node_rows = []
    for n in nodes:
        kb, count = key_bytes(anim[n])
        node_rows.append((n, len(blob), count))
        blob += kb
    its = items(sc, psp)
    lod_rows = []
    for lod in range(LODS):
        rows = []
        for it in its:
            nt = len(it['mesh']['tris'])
            target = nt if nt < SMALL else nt // (lod + 1)
            verts, tris = decimate.decimate(it['mesh'], target)
            vo = len(blob)
            blob += vert_bytes(verts, bases[it['tex']])
            to = len(blob)
            blob += b''.join(struct.pack('<3H', *t) for t in tris)
            blob += bytes(-len(blob) % 4)
            rows.append((vo, len(verts), to, len(tris)))
        lod_rows.append(rows)
        print('lod %dx: %d tris, %d verts' % (lod + 1, sum(r[3] for r in rows), sum(r[1] for r in rows)))
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'mix3.bin'), 'wb') as f:
        f.write(blob)
    write_layout(os.path.join(out, 'mix3_layout.zig'), len(atl) // atlas.WIDTH, palette, nodes, node_rows, its, lod_rows, bases)
    print('mix3.bin: %d bytes' % len(blob))


def write_layout(path, rows, palette, nodes, node_rows, its, lod_rows, bases):
    L = ['// GENERATED by tools/sb_mix3/convert.py from Suicide Barbie (TBL, MIT) mix3: do not edit.',
         '// The blob mix3.bin beside it holds what these offsets point at (format: convert.py).',
         'pub const Node = struct { off: u32, keys: u16 };',
         'pub const Mesh = struct { vert_off: u32, nverts: u16, tri_off: u32, ntris: u16 };',
         '/// layer: 0 drawn first (the backdrop), 1 next (the floor mark), 2 depth-sorted together.',
         '/// row0/size: the texture\'s slot in the atlas (env items make their uv from normals).',
         'pub const Item = struct { node: u8, env: bool, layer: u8, row0: u16, size: u16, name: []const u8 };',
         'pub const ATLAS_ROWS: u32 = %d;' % rows,
         'pub const CAMERA: u8 = %d;' % nodes.index('camera1'),
         'pub const nodes = [_]Node{']
    L += ['    .{ .off = %d, .keys = %d }, // %s' % (o, c, n) for n, o, c in node_rows]
    L += ['};', 'pub const items = [_]Item{']
    for it in its:
        row0, size = bases[it['tex']]
        layer = LAYERS.get(it['node'], 2)
        L.append('    .{ .node = %d, .env = %s, .layer = %d, .row0 = %d, .size = %d, .name = "%s" }, // %s' % (
            nodes.index(it['node']), 'true' if it['env'] else 'false', layer, row0, size, it['name'], it['tex']))
    L += ['};', 'pub const lods = [_][items.len]Mesh{']
    for rows_ in lod_rows:
        L.append('    .{ ' + ', '.join('.{ .vert_off = %d, .nverts = %d, .tri_off = %d, .ntris = %d }' % r for r in rows_) + ' },')
    L += ['};', 'pub const palette = [256][3]u8{']
    L += ['    ' + ' '.join('.{ %d, %d, %d },' % c for c in palette[i:i + 8]) for i in range(0, 256, 8)]
    L += ['};', '']
    with open(path, 'w') as f:
        f.write('\n'.join(L))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
