/// The glyph as eight row bytes, bit 7 = the leftmost pixel. Fails to compile on a malformed
/// picture, so a typo in the table cannot ship.
pub const ascii: [count][8]u8 = blk: {
    @setEvalBranchQuota(100_000);
    var out: [count][8]u8 = undefined;
    for (pictures, 0..) |pic, g| {
        if (pic.len != 63) @compileError("nfo_font: a glyph picture is 8 rows of 7 pixels and 7 slashes");
        for (0..8) |row| {
            var bits: u8 = 0;
            for (0..7) |col| {
                const c = pic[row * 8 + col];
                if (c != '#' and c != '.') @compileError("nfo_font: a picture holds only '#' and '.'");
                if (c == '#') bits |= @as(u8, 0x80) >> @intCast(col);
            }
            if (row < 7 and pic[row * 8 + 7] != '/') @compileError("nfo_font: rows are split by '/'");
            out[g][row] = bits;
        }
    }
    break :blk out;
};
